import {
  PREFIX,
  THEME_ATTRIBUTE,
  declarations,
  diffTokens,
  flattenTokens,
  tokenName,
} from './css-vars.js';
import { palette } from './palette.js';
import { darkTheme } from './themes/dark.js';
import { lightTheme } from './themes/light.js';

const HEADER = '/* Generated by @kerno/tokens — do not edit. */\n';

const attr = (value: string): string => `[${THEME_ATTRIBUTE}="${value}"]`;

/**
 * The global stylesheet shipped as `@kerno/tokens/tokens.css`:
 *
 * - `:root` carries the palette and the light theme.
 * - With no explicit theme, the root follows `prefers-color-scheme`.
 * - `[data-k-theme="light" | "dark" | "auto"]` scopes a theme to any subtree.
 * - `prefers-reduced-motion` collapses motion durations and decorative loops everywhere.
 */
export function generateTokensCss(): string {
  const paletteVars = flattenTokens(palette, `--${PREFIX}-palette`);
  const lightVars = flattenTokens(lightTheme.tokens);
  const darkDiff = diffTokens(lightTheme.tokens, darkTheme.tokens);

  const reducedMotion = [
    ...Object.keys(lightTheme.tokens.motion.duration).map(
      (k) => [tokenName(`motion.duration.${k}` as 'motion.duration.fast'), '0ms'] as const,
    ),
    // Decorative loops stop; busy spinners keep turning, slowly.
    [tokenName('motion.loop.pulse'), '0ms'] as const,
    [tokenName('motion.loop.spin'), '2200ms'] as const,
  ]
    .map(([name, value]) => `    ${name}: ${value} !important;`)
    .join('\n');

  return `${HEADER}
:root {
${declarations(paletteVars)}
}

:root,
${attr('light')},
${attr('auto')} {
  color-scheme: light;
${declarations(lightVars)}
}

@media (prefers-color-scheme: dark) {
  :root:not([${THEME_ATTRIBUTE}]),
  ${attr('auto')} {
    color-scheme: dark;
${declarations(darkDiff, '    ')}
  }
}

${attr('dark')} {
  color-scheme: dark;
${declarations(darkDiff)}
}

@media (prefers-reduced-motion: reduce) {
  :root,
  [${THEME_ATTRIBUTE}] {
${reducedMotion}
  }
}
`;
}

/**
 * Optional document baseline shipped as `@kerno/tokens/base.css`: applies
 * canvas background, text color and typography to the page and to any themed
 * subtree.
 */
export function generateBaseCss(): string {
  return `${HEADER}
:where(html),
:where([${THEME_ATTRIBUTE}]) {
  background-color: var(${tokenName('color.bg.canvas')});
  color: var(${tokenName('color.fg.default')});
  font-family: var(${tokenName('font.family.sans')});
  font-size: var(${tokenName('font.size.sm')});
  line-height: var(${tokenName('font.lineHeight.normal')});
  -webkit-font-smoothing: antialiased;
}
`;
}
